"""Build src/dw1_workbench/camera_engine.c into src/dw1_workbench/camera_engine_code.py (developer tool).

Needs clang, ld.lld, llvm-objcopy and llvm-nm (LLVM 15 or newer). The generated module holds the machine code,
its load address, the entry point and the SHA-256 of the C source, so running the workbench needs no compiler.
The output is checked for instructions the PS1's R3000 (MIPS I) cannot run, and for the R3000's HI/LO hazard:
a MULT/DIV within two instructions after MFHI/MFLO corrupts the result.
"""
from __future__ import annotations

import hashlib
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src" / "dw1_workbench" / "camera_engine.c"
OUTPUT = ROOT / "src" / "dw1_workbench" / "camera_engine_code.py"
LOAD_ADDRESS = 0x801D1000
LIMIT = 0x801D3000  # the Params block starts here
ENTRY = "zoom_render_tiles"
FLAGS = ["--target=mipsel-unknown-none-elf", "-march=mips1", "-mabi=32", "-mno-abicalls", "-fno-pic", "-G0", "-Os",
         "-ffreestanding", "-fno-builtin", "-nostdlib", "-mno-check-zero-division", "-fno-jump-tables",
         "-Wall", "-Werror"]


def check(code: bytes) -> None:
    words = struct.unpack(f"<{len(code) // 4}I", code)
    hazard = 0
    for index, word in enumerate(words):
        opcode, funct = word >> 26, word & 0x3F
        where = f"{LOAD_ADDRESS + index * 4:#x}: {word:08x}"
        if opcode in (0x14, 0x15, 0x16, 0x17):
            raise SystemExit(f"branch-likely (MIPS II) at {where}")
        if opcode in (0x30, 0x31, 0x32, 0x33, 0x34, 0x35, 0x36, 0x37, 0x38, 0x39, 0x3C, 0x3D, 0x3F) and opcode != 0x32:
            raise SystemExit(f"non-MIPS-I load/store at {where}")
        if opcode == 0x01 and (word >> 16) & 0x1F in (0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0E):
            raise SystemExit(f"trap instruction at {where}")
        if opcode == 0 and funct in (0x30, 0x31, 0x32, 0x33, 0x34, 0x36):
            raise SystemExit(f"trap instruction at {where}")
        if opcode == 0x1C:
            raise SystemExit(f"SPECIAL2 (MIPS32) instruction at {where}")
        if opcode == 0 and funct in (0x18, 0x19, 0x1A, 0x1B) and hazard:
            raise SystemExit(f"MULT/DIV within two instructions of MFHI/MFLO at {where}")
        hazard = 2 if opcode == 0 and funct in (0x10, 0x12) else max(0, hazard - 1)


def build() -> None:
    with tempfile.TemporaryDirectory() as folder:
        work = Path(folder)
        subprocess.run(["clang", *FLAGS, "-c", str(SOURCE), "-o", str(work / "engine.o")], check=True)
        subprocess.run(["ld.lld", "-Ttext", hex(LOAD_ADDRESS), "--no-relax", "-e", ENTRY, "-N",
                        str(work / "engine.o"), "-o", str(work / "engine.elf")], check=True)
        sections = subprocess.run(["llvm-objdump", "-h", str(work / "engine.elf")], check=True, capture_output=True,
                                  text=True).stdout
        for line in sections.splitlines():
            fields = line.split()
            if len(fields) >= 3 and fields[1] in (".data", ".bss", ".sdata", ".sbss", ".rodata") and int(fields[2], 16):
                if fields[1] != ".rodata":
                    raise SystemExit(f"the engine must not use {fields[1]}: put state in the Params block")
        subprocess.run(["llvm-objcopy", "-O", "binary", "--only-section=.text", "--only-section=.rodata",
                        str(work / "engine.elf"), str(work / "engine.bin")], check=True)
        symbols = subprocess.run(["llvm-nm", str(work / "engine.elf")], check=True, capture_output=True,
                                 text=True).stdout
        entry = next(int(line.split()[0], 16) for line in symbols.splitlines() if line.endswith(" " + ENTRY))
        code = (work / "engine.bin").read_bytes()
    if LOAD_ADDRESS + len(code) > LIMIT:
        raise SystemExit(f"engine is {len(code)} bytes; it must end before {LIMIT:#x}")
    check(code)
    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    lines = [f'"""Generated by tools/build_camera_engine.py from camera_engine.c; do not edit."""',
             f"SOURCE_SHA256 = \"{digest}\"", f"LOAD_ADDRESS = {LOAD_ADDRESS:#x}", f"ENTRY = {entry:#x}",
             "CODE = bytes.fromhex(", *(f'    "{code[i:i + 48].hex()}"' for i in range(0, len(code), 48)), ")", ""]
    OUTPUT.write_text("\n".join(lines))
    print(f"{len(code)} bytes at {LOAD_ADDRESS:#x}, entry {entry:#x}; wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(build())
